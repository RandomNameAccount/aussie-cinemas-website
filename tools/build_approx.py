#!/usr/bin/env python3
"""Approximate map placement for cinemas without a verified address point.

Places each unmapped cinema record, archive listing and research lead at the centre of its town or suburb,
using the GeoNames Australian postal-locality gazetteer (CC BY 4.0, geonames.org). These are approximate
locations and are labelled that way everywhere: on the map (dashed marker), in pop-ups, on record pages and
in Explore. Exact and address-point pins are never replaced by these.

Rules
  * exact town or suburb name within the same state (a few listed aliases such as "Brisbane CBD")
  * if one name has entries more than 10 km apart in that state, it is ambiguous and not placed
  * withheld records (licensing or provenance under review) are never placed
  * unpublished staging records are not included (only what the site already publishes)

  input   assets/map/cinema-sites.js, assets/data/leads-*.json, assets/data/archive-listings.json, archive-pins.json
          assets/data/au-localities.json   the localities used, extracted from GeoNames (refresh: --geonames AU.txt)
  output  assets/data/approx-placements.json   id -> {lat, lon, place, kind}
          assets/map/approx-points.js          map layer data
Run before tools/build_leads.py and tools/build_archive.py (tools/build_genuine.py runs all of them).
"""
import csv, glob, json, math, os, re, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
STATES = {"QLD", "NSW", "VIC", "TAS", "SA", "WA", "NT", "ACT"}
ALIAS = {("brisbane cbd", "QLD"): "brisbane city", ("civic", "ACT"): "city", ("canberra city", "ACT"): "city",
         ("sydney cbd", "NSW"): "sydney", ("melbourne cbd", "VIC"): "melbourne", ("adelaide cbd", "SA"): "adelaide", ("perth cbd", "WA"): "perth"}
LOC_FILE = "assets/data/au-localities.json"

def norm(s):
    s = unicodedata.normalize("NFKD", s or "").encode("ascii", "ignore").decode().lower()
    s = re.sub(r"\bst\.?\s", "saint ", s); s = re.sub(r"\bmt\.?\s", "mount ", s)
    s = s.replace("&", " and "); s = re.sub(r"[^a-z0-9 ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()
def km(a, b):
    p = math.radians
    return 6371 * math.acos(min(1, math.sin(p(a[0])) * math.sin(p(b[0])) + math.cos(p(a[0])) * math.cos(p(b[0])) * math.cos(p(a[1] - b[1]))))

raw = open("assets/map/cinema-sites.js", encoding="utf-8").read()
SITES = json.loads(raw[raw.index("window.APA_SITES = ") + 19:].strip().rstrip(";"))["sites"]
LEADS = [l for f in sorted(glob.glob("assets/data/leads-*.json")) for l in json.load(open(f, encoding="utf-8"))]
ARCH = json.load(open("assets/data/archive-listings.json", encoding="utf-8")) if os.path.exists("assets/data/archive-listings.json") else []
PINNED = {p["id"] for p in json.load(open("assets/data/archive-pins.json", encoding="utf-8"))} if os.path.exists("assets/data/archive-pins.json") else set()
ITEMS = ([("record", s["id"], s["name"], s["suburb"], s["state"]) for s in SITES if s["loc"]["kind"] == "none"] +
         [("archive", a["id"], a["name"], a["locality"], a["state"]) for a in ARCH if a["id"] not in PINNED] +
         [("lead", l["id"], l["name"], l["locality"], l["state"]) for l in LEADS if not l.get("noApprox")])
def key(loc, st):
    k = norm(loc); return ALIAS.get((k, st), k) + "|" + st

if "--geonames" in sys.argv:   # refresh the locality extract from a GeoNames AU postal file
    src = sys.argv[sys.argv.index("--geonames") + 1]
    idx = {}
    for r in csv.reader(open(src, encoding="utf-8"), delimiter="\t"):
        if len(r) >= 11 and r[4] in STATES and r[9]:
            idx.setdefault(norm(r[2]) + "|" + r[4], []).append([float(r[9]), float(r[10]), r[2]])
    want = {key(loc, st) for _, _, _, loc, st in ITEMS}
    json.dump({k: idx[k] for k in sorted(want) if k in idx}, open(LOC_FILE, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
LOCS = json.load(open(LOC_FILE, encoding="utf-8"))

placed, layer, missed = {}, [], []
for kind, i, name, loc, st in ITEMS:
    c = LOCS.get(key(loc, st)) if loc and st in STATES else None
    if not c or any(km(c[0][:2], x[:2]) > 10 for x in c[1:]):
        missed.append(f"{kind} {i} ({loc}, {st})"); continue
    lat = round(sum(x[0] for x in c) / len(c), 4); lon = round(sum(x[1] for x in c) / len(c), 4)
    assert -44.5 < lat < -9 and 112 < lon < 154.5, i
    placed[i] = {"lat": lat, "lon": lon, "place": f"{c[0][2]}, {st}", "kind": kind}
    layer.append({"id": i, "kind": kind, "name": name, "place": f"{c[0][2]}, {st}", "lat": lat, "lon": lon})
json.dump(placed, open("assets/data/approx-placements.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0, sort_keys=True)
open("assets/map/approx-points.js", "w", encoding="utf-8").write(
    "/* Generated by tools/build_approx.py. Approximate (town or suburb centre) locations; GeoNames, CC BY 4.0. Do not edit. */\n"
    "window.APA_APPROX = " + json.dumps(layer, ensure_ascii=False, separators=(",", ":")) + ";\n")
from collections import Counter
print(f"{len(layer)} approximate placements ({', '.join(f'{k} {v}' for k, v in Counter(x['kind'] for x in layer).items())}); "
      f"{len(missed)} not placed (no unambiguous town match)")
